export const paquetePorId = (id: string) => PAQUETES.find((p) => p.id === id);
export const lineaPorId = (id: string) => LINEAS.find((l) => l.id === id)!;
export const familiaPorId = (id: string) => FAMILIAS.find((f) => f.id === id)!;
export const familiaDePaquete = (p: Paquete) => familiaPorId(lineaPorId(p.linea).familia);
export const moduloPorId = (id: string) => MODULOS.find((m) => m.id === id);
export const paquetesDeLinea = (linea: string) => PAQUETES.filter((p) => p.linea === linea);

/** Paquete anterior dentro de su línea (para «diferencia con el nivel anterior»). */
export function nivelAnterior(p: Paquete): Paquete | undefined {
  const hermanos = paquetesDeLinea(p.linea);
  const i = hermanos.findIndex((x) => x.id === p.id);
  return i > 0 ? hermanos[i - 1] : undefined;
}
